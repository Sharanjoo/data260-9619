"""HW10 Part 2.2: the four judging criteria as DeepEval GEval metrics.

Scale (identical for the judge and for the human labels in Part 3): 1 = very poor ... 5 = excellent.
GEval's own score is (g - 1) / 4 in [0, 1] when the rubric runs 1..5; to_scale() turns it back into the 1-5 number.
The evaluation steps are FIXED text (not generated by the judge), so two runs differ only through the judge's answer.
"""
from __future__ import annotations

from typing import Any, Dict, List, Optional

from deepeval.metrics import GEval
from deepeval.metrics.g_eval import Rubric
from deepeval.test_case import LLMTestCase, SingleTurnParams

SCALE = (1, 5)

RUBRIC = [
    Rubric(score_range=(1, 1), expected_outcome="Very poor: wrong, unsafe, off-topic or empty."),
    Rubric(score_range=(2, 2), expected_outcome="Poor: misses most of what the shopper needs or has a serious error."),
    Rubric(score_range=(3, 3), expected_outcome="Fair: partly useful but incomplete, vague or with a minor error."),
    Rubric(score_range=(4, 4), expected_outcome="Good: useful, correct and safe, with a small gap."),
    Rubric(score_range=(5, 5), expected_outcome="Excellent: complete, correct, safe, clear and actionable."),
]

HELPFULNESS_STEPS = [
    "Read the shopper's question (it may include a block of recall facts). Decide what the shopper needs to do.",
    "Check that the answer tells the shopper what to do with the product they already have, and why it matters.",
    "Check every concrete detail in the answer (product, lot code, dates, reason, remedy) against the facts in the "
    "question. Penalise any detail that is not supported, and any invented lot code, date, phone number or web address.",
    "Penalise answers that are vague, off-topic, unsafe (telling the shopper to eat or use a recalled product) or "
    "that ignore part of the question.",
    "Give a whole number from 1 to 5 using the rubric, and one or two sentences of reason.",
]

PLAN_STEPS = [
    "Read the shopper's question (it may include recall facts). The plan is a short list of steps a writer will follow.",
    "Check that the steps cover what the shopper needs: identify the product and recall reason, say what to do with "
    "the product they already have, and point to the official notice or remedy.",
    "Check that the steps are specific to this question, in a sensible order, and short enough to act on.",
    "Penalise steps that are generic filler, off-topic, repeat each other, or that invent facts not in the question.",
    "Give a whole number from 1 to 5 using the rubric, and one or two sentences of reason.",
]


def _geval(name: str, steps: List[str], params: List[Any], judge: Any) -> GEval:
    return GEval(name=name, evaluation_steps=steps, evaluation_params=params, rubric=RUBRIC, model=judge,
                 async_mode=False, verbose_mode=False)


def build_metrics(judge: Any) -> Dict[str, GEval]:
    io = [SingleTurnParams.INPUT, SingleTurnParams.ACTUAL_OUTPUT]
    return {
        "plan_quality": _geval("Plan Quality", PLAN_STEPS, io, judge),
        "writer_helpfulness": _geval("Writer Helpfulness", HELPFULNESS_STEPS, io, judge),
        "final_helpfulness": _geval("Final Answer Helpfulness", HELPFULNESS_STEPS, io, judge),
    }


def to_scale(score: Optional[float]) -> Optional[int]:
    """GEval score in [0, 1] -> the 1-5 scale (clamped)."""
    if score is None:
        return None
    return max(SCALE[0], min(SCALE[1], round(SCALE[0] + (SCALE[1] - SCALE[0]) * float(score))))


def score_one(metric: GEval, question: str, output: str) -> Dict[str, Any]:
    """Run one metric; never raises: a failure comes back as score=None with the error text."""
    try:
        metric.measure(LLMTestCase(input=question, actual_output=output), _show_indicator=False)
        if not -1e-9 <= float(metric.score) <= 1 + 1e-9:  # the judge answered outside 1-5: not a usable score
            raise ValueError(f"judge score out of the 1-5 range (GEval score {float(metric.score):.2f})")
        return {"score": to_scale(metric.score), "raw": float(metric.score), "reason": (metric.reason or "").strip(),
                "error": None}
    except Exception as exc:  # noqa: BLE001 - JudgeError, timeouts, anything the metric raises
        return {"score": None, "raw": None, "reason": "", "error": f"{type(exc).__name__}: {exc}"}
